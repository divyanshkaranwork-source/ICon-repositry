function tokens(t) {
  const rule = (scope, foreground, fontStyle) => ({ scope, settings: { foreground, ...(fontStyle ? { fontStyle } : {}) } });
  return [
    rule(['comment', 'punctuation.definition.comment', 'string.comment'], t.comment, 'italic'),
    rule(['keyword', 'keyword.control', 'keyword.other', 'storage.modifier', 'keyword.operator.new', 'keyword.operator.expression', 'keyword.operator.logical.python'], t.keyword),
    rule(['storage', 'storage.type', 'keyword.declaration', 'keyword.function'], t.storage, 'italic'),
    rule(['string', 'string.quoted', 'string.template', 'markup.inline.raw'], t.string),
    rule(['constant.numeric', 'keyword.other.unit'], t.number),
    rule(['constant', 'constant.language', 'support.constant', 'variable.other.constant', 'variable.other.enummember'], t.constant),
    rule(['entity.name.function', 'support.function', 'meta.function-call', 'variable.function', 'entity.name.method'], t.func),
    rule(['entity.name.type', 'entity.name.class', 'support.type', 'support.class', 'entity.other.inherited-class', 'storage.type.class', 'entity.name.namespace', 'meta.type.annotation'], t.type),
    rule(['variable', 'variable.other.readwrite', 'meta.definition.variable'], t.variable),
    rule(['variable.other.property', 'variable.other.object.property', 'support.variable.property', 'meta.object-literal.key', 'entity.name.tag.yaml', 'support.type.property-name'], t.property),
    rule(['variable.parameter', 'meta.parameter'], t.parameter, 'italic'),
    rule(['variable.language', 'variable.language.this', 'variable.language.self', 'variable.language.super'], t.keyword, 'italic'),
    rule(['entity.name.tag', 'meta.tag.sgml', 'punctuation.definition.tag'], t.tag),
    rule(['entity.other.attribute-name', 'entity.other.attribute-name.class.css', 'entity.other.attribute-name.id.css'], t.attribute),
    rule(['punctuation', 'meta.brace', 'punctuation.separator', 'punctuation.terminator'], t.punctuation),
    rule(['keyword.operator', 'punctuation.accessor', 'keyword.operator.assignment'], t.operator),
    rule(['string.regexp', 'constant.other.character-class.regexp'], t.regex),
    rule(['constant.character.escape', 'constant.other.placeholder'], t.escape),
    rule(['support.type.property-name.css', 'support.type.vendored.property-name'], t.property),
    rule(['support.constant.property-value.css', 'support.constant.color', 'constant.other.color'], t.number),
    rule(['entity.other.attribute-name.pseudo-class', 'entity.other.attribute-name.pseudo-element'], t.escape),
    rule(['meta.decorator', 'punctuation.decorator', 'entity.name.function.decorator', 'meta.annotation'], t.escape, 'italic'),
    rule(['markup.heading', 'entity.name.section', 'markup.heading punctuation.definition.heading'], t.heading, 'bold'),
    rule(['markup.bold'], t.type, 'bold'),
    rule(['markup.italic'], t.parameter, 'italic'),
    rule(['markup.underline.link', 'string.other.link', 'markup.link'], t.link, 'underline'),
    rule(['markup.quote'], t.comment, 'italic'),
    rule(['markup.list punctuation.definition.list'], t.keyword),
    rule(['markup.inserted'], t.string),
    rule(['markup.deleted'], t.invalid),
    rule(['markup.changed'], t.property),
    rule(['invalid', 'invalid.illegal'], t.invalid),
    rule(['support.type.property-name.json'], t.property),
    rule(['support.type.property-name.json.comments'], t.property),
    rule(['entity.name.function.macro', 'meta.preprocessor', 'keyword.control.directive'], t.escape),
    rule(['entity.name.label', 'entity.name.tag.reference'], t.attribute),
  ];
}

export function buildColorThemes() {
  return Object.entries(palettes).map(([key, p]) => ({
    key,
    label: p.name,
    uiTheme: p.type === 'dark' ? 'vs-dark' : 'vs',
    json: {
      $schema: 'vscode://schemas/color-theme',
      name: p.name,
      type: p.type,
      semanticHighlighting: true,
      colors: workbench(p),
      tokenColors: tokens(p.tokens),
      semanticTokenColors: {
        parameter: { foreground: p.tokens.parameter, italic: true },
        property: p.tokens.property,
        'property.readonly': p.tokens.property,
        enumMember: p.tokens.constant,
        'variable.readonly': p.tokens.constant,
        'variable.defaultLibrary': p.tokens.type,
        type: p.tokens.type,
        class: p.tokens.type,
        interface: p.tokens.type,
        typeParameter: { foreground: p.tokens.type, italic: true },
        namespace: p.tokens.type,
        function: p.tokens.func,
        method: p.tokens.func,
        decorator: { foreground: p.tokens.escape, italic: true },
        macro: p.tokens.escape,
      },
    },
  }));
}
